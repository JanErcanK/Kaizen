// Regenerate after editing the reviewed selection and its source metadata.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const foods = JSON.parse(fs.readFileSync(path.join(__dirname, 'data/standard_food_catalog.json'), 'utf8'));
const quote = s => "'" + s.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$') + "'";
if (foods.length !== 300 || new Set(foods.map(f => f.nameDe)).size !== 300 || new Set(foods.map(f => f.nameEn.toLowerCase())).size !== 300) {
  throw Error('Expected exactly 300 distinct bilingual foods');
}
const entries = foods.map(f => {
  for (const k of ['proteinG', 'carbsG', 'fatsG']) {
    if (!Number.isFinite(f[k]) || f[k] < 0 || f[k] > 100) throw Error(`${f.nameDe}: invalid ${k}`);
  }
  return '  StandardFoodEntry(\n' + Object.entries(f).filter(([k]) => k !== 'sourceName').map(([k,v]) => `    ${k}: ${typeof v === 'number' ? v : quote(v)},`).join('\n') + '\n  ),';
});
fs.writeFileSync(path.join(root, 'lib/data/standard_food_catalog.dart'),
  "// Generated by tool/generate_standard_food_catalog.cjs.\n" +
  "// Sources and preparation conventions: docs/FOOD_CATALOG_SOURCES.txt\n" +
  "import 'standard_food_entry.dart';\n\n" +
  'const standardFoodEntries = <StandardFoodEntry>[\n' + entries.join('\n') + '\n];\n\n' +
  'final standardFoodsByName = {\n  for (final food in standardFoodEntries) food.nameDe: food,\n};\n');
console.log(`Generated ${foods.length} standard foods.`);
