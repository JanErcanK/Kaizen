  static String text(String germanCanonical, {required String english}) {
    return ProgressStore.useGerman
        ? normalizeGermanSpelling(germanCanonical)
        : english;
  }

  static String foodName(String germanCanonical) {
    final key = canonicalFoodName(normalizeGermanSpelling(germanCanonical));
    if (key == 'Hühnereier') {
      return text('Hühnerei', english: 'Chicken egg');
    }
    return text(
      key,
      english: standardFoodsByName[key]?.nameEn ?? foodEnglishNames[key] ??
          foodEnglishNames[germanCanonical] ??
          key,
    );
  }

  static String foodSubtitle(String foodName) {
    final key = canonicalFoodName(normalizeGermanSpelling(foodName));
    final standard = standardFoodsByName[key];
    if (standard != null) {
      return text(standard.subtitleDe, english: standard.subtitleEn);
    }
    final german = foodGermanSubtitles[key] ??
        foodGermanSubtitles[foodName] ??
        key;
    return text(
      german,
      english: foodEnglishSubtitles[key] ??
          foodEnglishSubtitles[foodName] ??
          german,
    );
  }

