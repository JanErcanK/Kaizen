  /// Resolves gym, calisthenics, or timed-workout exercise names for display.
  static String anyExerciseName(String germanName) {
    final key = normalizeGermanSpelling(germanName);
    if (ProgressStore.useGerman) return key;
    return workoutExerciseEnglishNames[key] ??
        gymExerciseEnglishNames[key] ??
        calisthenicsExerciseEnglishNames[key] ??
        workoutExerciseEnglishNames[germanName] ??
        gymExerciseEnglishNames[germanName] ??
        calisthenicsExerciseEnglishNames[germanName] ??
        key;
  }

  /// English alias for a German exercise name (any catalog), if known.
  static String? exerciseEnglishAlias(String germanName) {
    final key = normalizeGermanSpelling(germanName);
    return workoutExerciseEnglishNames[key] ??
        gymExerciseEnglishNames[key] ??
        calisthenicsExerciseEnglishNames[key] ??
        workoutExerciseEnglishNames[germanName] ??
        gymExerciseEnglishNames[germanName] ??
        calisthenicsExerciseEnglishNames[germanName];
  }

  /// English alias for a German food name, if known.
  static String? foodEnglishAlias(String germanCanonical) {
    final key = canonicalFoodName(normalizeGermanSpelling(germanCanonical));
    return standardFoodsByName[key]?.nameEn ??
        foodEnglishNames[key] ?? foodEnglishNames[germanCanonical];
  }
  /// Description for gym or calisthenics catalog entries.
  static String anyExerciseDescription(String germanName, {String? kind}) {
    if (kind == 'calisthenics') {
      return calisthenicsDescription(germanName);
    }
    if (kind == 'gym') {
      return gymDescription(germanName);
    }
    final gym = gymGermanDescriptions[germanName];
    if (gym != null) return gymDescription(germanName);
    if (calisthenicsGermanDescriptions.containsKey(germanName) ||
        calisthenicsExerciseEnglishNames.containsKey(germanName)) {
      return calisthenicsDescription(germanName);
    }
    return gymDescription(germanName);
  }

  /// True if [query] matches the German canonical name and/or its English alias.
  /// Matching is always bilingual — independent of the active UI locale.
  static bool matchesLocalizedName({
    required String germanCanonical,
    required String query,
    String? englishAlias,
  }) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return true;
    final german = germanCanonical.toLowerCase();
    if (german.contains(q)) return true;
    final english = (englishAlias ?? '').toLowerCase();
    if (english.isNotEmpty && english.contains(q)) return true;
    return false;
  }

  static bool matchesFoodQuery(
    String germanName,
    String query, {
    String subtitle = '',
    Iterable<String> tags = const [],
    Iterable<String> focuses = const [],
    String macro = '',
  }) {
    final key = canonicalFoodName(normalizeGermanSpelling(germanName));
    final standard = standardFoodsByName[key];
    return matchesFoodSearch([
      germanName, key, foodEnglishAlias(key) ?? '',
      foodSearchAliases[key] ?? '', standard?.aliases ?? '',
      standard?.categoryDe ?? '', standard?.categoryEn ?? '',
      subtitle, foodGermanSubtitles[key] ?? '',
      foodEnglishSubtitles[key] ?? '',
      for (final tag in tags) ...[
        tag, foodTagGerman[tag] ?? '', foodTagEnglish[tag] ?? '',
      ],
      for (final focus in focuses) ...[
        focus,
        if (focus == 'healthy_brain') 'gehirngesund healthy brain',
        if (focus == 'never_eat') 'nie essen never eat',
      ],
      macro,
      if (macro == 'carbs') 'kohlenhydrate carbohydrates',
      if (macro == 'fats') 'fette fats',
      if (macro == 'protein') 'eiweiß protein',
    ].join(' '), query);
  }

  static bool matchesExerciseQuery(String germanName, String query) {
    final key = normalizeGermanSpelling(germanName);
    return matchesLocalizedName(
          germanCanonical: key,
          query: query,
          englishAlias: exerciseEnglishAlias(key),
        ) ||
        matchesLocalizedName(
          germanCanonical: germanName,
          query: query,
          englishAlias: exerciseEnglishAlias(germanName),
        );
  }

  static String exerciseFallback() =>
      ProgressStore.useGerman ? 'Übung' : 'Exercise';

  static String foodTag(String tagId) {
    return text(
      foodTagGerman[tagId] ?? tagId,
      english: foodTagEnglish[tagId] ?? tagId,
    );
  }

  static String foodFocus(String focusId) {
    return switch (focusId) {
      'never_eat' => text('Nie essen', english: 'Never eat'),
      'healthy_brain' => text('Gehirngesund', english: 'Healthy brain'),
      _ => focusId.replaceAll('_', ' '),
    };
  }

